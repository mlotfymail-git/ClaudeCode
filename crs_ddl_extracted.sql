    PROCEDURE bill_agreement (p_agrm_id IN NUMBER, p_to_date IN DATE) IS 
        v_nr          NUMBER := 0; 
        v_prv_bill    NUMBER := 0; 
        v_prv_to_date DATE; 
        v_bill_id     NUMBER; 
        v_com_id      NUMBER; 
        v_loc_id      NUMBER; 
        v_tax_pct     NUMBER := get_tax_percent(C_DEFAULT_TAX_CODE); 
    BEGIN 
        -- Reject if any unvalidated bill exists for this agreement 
        SELECT COUNT(BILL_ID) INTO v_nr 
        FROM   CRS_BILL_HDRS 
        WHERE  AGRM_ID = p_agrm_id AND BILL_STATUS = 1; 
 
        IF v_nr > 0 THEN 
            RAISE_APPLICATION_ERROR(-20000, 'Unvalidated invoice(s) exist for this agreement.'); 
        END IF; 
 
        -- Find the start date for this billing run 
        SELECT COUNT(BILL_ID), MAX(BILL_ID) INTO v_nr, v_prv_bill 
        FROM   CRS_BILL_HDRS 
        WHERE  AGRM_ID = p_agrm_id AND BILL_STATUS >= 2; 
 
        IF v_nr > 0 THEN 
            SELECT TRUNC(TO_DATE, 'DD') + 1 INTO v_prv_to_date 
            FROM   CRS_BILL_HDRS 
            WHERE  AGRM_ID = p_agrm_id AND BILL_ID = v_prv_bill; 
        ELSE 
            SELECT MIN(CHECK_DATE) INTO v_prv_to_date 
            FROM   CRS_AGRM_CHECKING 
            WHERE  AGRM_ID = p_agrm_id AND CHECK_STATUS > 1; 
        END IF; 
 
        IF p_to_date <= v_prv_to_date THEN 
            RETURN; -- Nothing to bill 
        END IF; 
 
        SELECT COUNT(1) INTO v_nr 
        FROM   V_CRS_CHECK_OUT_IN 
        WHERE  AGRM_ID   = p_agrm_id 
        AND    OUT_DATE  <= p_to_date 
        AND    (IN_DATE BETWEEN v_prv_to_date AND p_to_date OR IN_DATE IS NULL); 
 
        IF v_nr = 0 THEN 
            RETURN; -- No movements to bill 
        END IF; 
 
        SELECT COM_ID, LOC_ID INTO v_com_id, v_loc_id 
        FROM   CRS_AGREEMENTS WHERE AGRM_ID = p_agrm_id; 
 
        INSERT INTO CRS_BILL_HDRS 
            (COM_ID, LOC_ID, BILL_DATE, DUE_DATE, BILL_TYPE, REMARKS, 
             AGRM_ID, FROM_DATE, TO_DATE, BILL_STATUS) 
        VALUES 
            (v_com_id, v_loc_id, p_to_date, p_to_date, 1, 
             'Invoice: ' || TO_CHAR(v_prv_to_date,'DD-MON-YYYY') 
             || ' to ' || TO_CHAR(p_to_date,'DD-MON-YYYY'), 
             p_agrm_id, v_prv_to_date, p_to_date, 1) 
        RETURNING BILL_ID INTO v_bill_id; 
 
        FOR agrm IN (SELECT * FROM CRS_AGREEMENTS WHERE AGRM_ID = p_agrm_id) LOOP 
 
            -- Lines for returned vehicles 
            FOR chk IN ( 
                SELECT * FROM V_CRS_CHECK_OUT_IN 
                WHERE  AGRM_ID  = p_agrm_id 
                AND    OUT_DATE <= p_to_date 
                AND    IN_DATE  BETWEEN v_prv_to_date AND p_to_date 
                ORDER  BY CHECK_OUT_ID, CHECK_IN_ID 
            ) LOOP 
                INSERT INTO CRS_BILL_LINES 
                    (BILL_ID, ACCT_ID, DESC_EN, DESC_AR, FROM_DATE, TO_DATE, 
                     RENT_UNIT, UNIT_NOS, UNIT_RATE, DISC_PERC, 
                     TAX_IDS, TAX_PERCENT, CHECK_IN_ID, CHECK_OUT_ID, SRC_FROM) 
                VALUES ( 
                    v_bill_id, 1, 
                    'Rent: ' || chk.VIN 
                    || ' from ' || TO_CHAR(GREATEST(v_prv_to_date, chk.OUT_DATE),'DD-MM-YYYY') 
                    || ' to '   || TO_CHAR(LEAST(p_to_date, chk.IN_DATE),        'DD-MM-YYYY'), 
                    'ايجار: '  || chk.VIN 
                    || ' من '  || TO_CHAR(GREATEST(v_prv_to_date, chk.OUT_DATE),'DD-MM-YYYY') 
                    || ' إلى ' || TO_CHAR(LEAST(p_to_date, chk.IN_DATE),        'DD-MM-YYYY'), 
                    GREATEST(v_prv_to_date, chk.OUT_DATE), 
                    LEAST(p_to_date, chk.IN_DATE), 
                    'D', 
                    LEAST(p_to_date, chk.IN_DATE) - GREATEST(v_prv_to_date, chk.OUT_DATE), 
                    agrm.RENTAL_RATE, agrm.DISC_PERC, 
                    C_DEFAULT_TAX_CODE, v_tax_pct, 
                    chk.CHECK_IN_ID, chk.CHECK_OUT_ID, '2' 
                ); 
            END LOOP; 
 
            -- Lines for vehicles still out (not yet returned) 
            FOR chk IN ( 
                SELECT * FROM V_CRS_CHECK_OUT_IN 
                WHERE  AGRM_ID  = p_agrm_id 
                AND    OUT_DATE <= p_to_date 
                AND    IN_DATE IS NULL 
                ORDER  BY CHECK_OUT_ID 
            ) LOOP 
                INSERT INTO CRS_BILL_LINES 
                    (BILL_ID, ACCT_ID, DESC_EN, DESC_AR, FROM_DATE, TO_DATE, 
                     RENT_UNIT, UNIT_NOS, UNIT_RATE, DISC_PERC, 
                     TAX_IDS, TAX_PERCENT, CHECK_IN_ID, CHECK_OUT_ID, SRC_FROM) 
                VALUES ( 
                    v_bill_id, 1, 
                    'Rent: ' || chk.VIN 
                    || ' from ' || TO_CHAR(GREATEST(v_prv_to_date, chk.OUT_DATE),'DD-MM-YYYY') 
                    || ' to '   || TO_CHAR(p_to_date,'DD-MM-YYYY'), 
                    'ايجار: '  || chk.VIN 
                    || ' من '  || TO_CHAR(GREATEST(v_prv_to_date, chk.OUT_DATE),'DD-MM-YYYY') 
                    || ' إلى ' || TO_CHAR(p_to_date,'DD-MM-YYYY'), 
                    GREATEST(v_prv_to_date, chk.OUT_DATE), p_to_date, 
                    'D', 
                    p_to_date - GREATEST(v_prv_to_date, chk.OUT_DATE) + 1, 
                    agrm.RENTAL_RATE, agrm.DISC_PERC, 
                    C_DEFAULT_TAX_CODE, v_tax_pct, 
                    chk.CHECK_IN_ID, chk.CHECK_OUT_ID, '1' 
                ); 
            END LOOP; 
        END LOOP; 
 
        validate_bill(p_bill_id => v_bill_id); 
 
    END bill_agreement; 
 
