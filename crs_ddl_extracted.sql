    PROCEDURE complete_checking (p_check_id IN NUMBER) IS 
        v_meter_used    NUMBER; 
        v_fuel_less     NUMBER; 
        v_days          NUMBER; 
        v_km_limit      NUMBER; 
        v_km_rate       NUMBER; 
        v_fuel_rate     NUMBER; 
        v_rate_type     VARCHAR2(3); 
        v_full_limit_km NUMBER; 
        v_part_cost     NUMBER; 
        v_part_name_ar  VARCHAR2(200); 
        v_part_name_en  VARCHAR2(200); 
        -- Account IDs resolved from lookup (no hardcoding) 
        v_acct_fuel     NUMBER := get_acct_id(C_PURPOSE_FUEL); 
        v_acct_overlim  NUMBER := get_acct_id(C_PURPOSE_OVERLIMIT); 
        v_acct_lost     NUMBER := get_acct_id(C_PURPOSE_LOST_ITEM); 
    BEGIN 
        FOR r IN ( 
            SELECT checking_id, loc_id, agrm_id, reason_id, 
                   vin, out_in, check_date, meter_km, fuel_mtr 
            FROM   CRS_AGRM_CHECKING 
            WHERE  checking_id = p_check_id 
        ) LOOP 
 
            -- ---------------------------------------------------------------- 
            -- Over-limit KM charge (closing check-in only) 
            -- ---------------------------------------------------------------- 
            IF r.out_in = 'IN' AND r.reason_id IN (2, 5) THEN 
                SELECT SUM(meter_in - meter_out), SUM(NVL(daysh_out, 0)) 
                INTO   v_meter_used, v_days 
                FROM   V_CRS_CHECK_OUT_IN 
                WHERE  agrm_id = r.agrm_id; 
 
                SELECT METER_LIMIT, OVRKM_RATE, RATE_TYPE 
                INTO   v_km_limit, v_km_rate, v_rate_type 
                FROM   CRS_AGREEMENTS 
                WHERE  AGRM_ID = r.agrm_id; 
 
                -- Pro-rate the km allowance by actual rental duration 
                SELECT ROUND(v_days / DECODE(v_rate_type,'D',1,'W',7,'M',30,'Y',365) * v_km_limit) 
                INTO   v_full_limit_km 
                FROM   DUAL; 
 
                IF v_meter_used > v_full_limit_km THEN 
                    INSERT INTO CRS_CHECK_CHARGES 
                        (CHECKING_ID, ACCT_ID, DESC_EN, DESC_AR, NET_AMNT, NOTES) 
                    VALUES ( 
                        p_check_id, 
                        v_acct_overlim, 
                        'Over Limit KM: ' || (v_meter_used - v_full_limit_km) || ' KM @ ' || v_km_rate, 
                        'رسوم كم زيادة: '  || (v_meter_used - v_full_limit_km) || ' كم @ ' || v_km_rate, 
                        (v_meter_used - v_full_limit_km) * v_km_rate, 
                        NULL 
                    ); 
                END IF; 
            END IF; 
 
            -- ---------------------------------------------------------------- 
            -- Fuel charge (any check-in) 
            -- ---------------------------------------------------------------- 
            IF r.out_in = 'IN' THEN 
                BEGIN 
                    SELECT fuel_out - fuel_in 
                    INTO   v_fuel_less 
                    FROM   V_CRS_CHECK_OUT_IN 
                    WHERE  check_in_id = p_check_id; 
                EXCEPTION 
                    WHEN NO_DATA_FOUND THEN v_fuel_less := 0; 
                END; 
 
                IF v_fuel_less > 10 THEN 
                    SELECT PC.FUEL_RATE 
                    INTO   v_fuel_rate 
                    FROM   CRS_PRICE_CATG PC 
                    JOIN   CRS_AGREEMENTS A ON A.PRICE_CATG_ID = PC.PRICE_CATG_ID 
                                           AND A.COM_ID         = PC.COM_ID 
                    WHERE  A.AGRM_ID = r.agrm_id; 
 
                    INSERT INTO CRS_CHECK_CHARGES 
                        (CHECKING_ID, ACCT_ID, DESC_EN, DESC_AR, NET_AMNT, NOTES) 
                    VALUES ( 
                        p_check_id, 
                        v_acct_fuel, 
                        'Fuel shortage from checkout level: ' || v_fuel_less || '% @ ' || v_fuel_rate, 
                        'استهلاك وقود من مستوى التسليم: '    || v_fuel_less || '% @ ' || v_fuel_rate, 
                        ROUND(v_fuel_less / 100 * v_fuel_rate, 2), 
                        NULL 
                    ); 
                END IF; 
 
                -- -------------------------------------------------------------- 
                -- Missing inventory items 
                -- -------------------------------------------------------------- 
                FOR inv IN ( 
                    SELECT * FROM CRS_CHECK_INVENTORY 
                    WHERE  checking_id = p_check_id 
                    AND    part_exist  = 'N' 
                    ORDER  BY line_id 
                ) LOOP 
                    SELECT PART_COST, PART_AR, PART_EN 
                    INTO   v_part_cost, v_part_name_ar, v_part_name_en 
                    FROM   CRS_CHECK_PARTS 
                    WHERE  PART_ID  = inv.part_id 
                    AND    LIST_ID  = 'INV'; 
 
                    INSERT INTO CRS_CHECK_CHARGES 
                        (CHECKING_ID, ACCT_ID, DESC_EN, DESC_AR, NET_AMNT, NOTES) 
                    VALUES ( 
                        p_check_id, 
                        v_acct_lost, 
                        'Missing item: ' || v_part_name_en || ' @ ' || v_part_cost, 
                        'عنصر مفقود: '   || v_part_name_ar || ' @ ' || v_part_cost, 
                        v_part_cost, 
                        NULL 
                    ); 
                END LOOP; 
            END IF; 
 
            -- Mark checking as completed (status 5) 
            UPDATE CRS_AGRM_CHECKING 
            SET    CHECK_STATUS = 5 
            WHERE  CHECKING_ID  = p_check_id; 
 
        END LOOP; 
    END complete_checking; 
 
