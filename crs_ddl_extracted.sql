    PROCEDURE checking_to_drnote (p_check_id IN NUMBER, r_drnote_id OUT NUMBER) IS 
        v_tax_pct NUMBER := get_tax_percent(C_DEFAULT_TAX_CODE); 
    BEGIN 
        FOR c IN ( 
            SELECT agrm_id, cust_id, checking_id, doc_ref, vin, 
                   loc_id, com_id, check_date 
            FROM   V_CRS_AGRM_CHECKING 
            WHERE  checking_id = p_check_id 
        ) LOOP 
            INSERT INTO CRS_DRNOTE_HDRS 
                (DRNOTE_DATE, DUE_DATE, COM_ID, LOC_ID, CUST_ID, 
                 AGRM_ID, DRNOTE_TYPE, DRNOTE_STATUS) 
            VALUES 
                (c.check_date, c.check_date, c.com_id, c.loc_id, 
                 c.cust_id, c.agrm_id, 1, 1) 
            RETURNING DRNOTE_ID INTO r_drnote_id; 
 
            FOR r IN ( 
                SELECT checking_id, line_id, acct_id, 
                       desc_en, desc_ar, net_amnt, notes 
                FROM   CRS_CHECK_CHARGES 
                WHERE  checking_id = p_check_id 
                ORDER  BY line_id 
            ) LOOP 
                INSERT INTO CRS_DRNOTE_LINES 
                    (DRNOTE_ID, CHECKING_ID, ACCT_ID, DESC_EN, DESC_AR, 
                     UNIT_RATE, UNIT_NOS, TAX_IDS, TAX_PERCENT, NOTES) 
                VALUES 
                    (r_drnote_id, r.checking_id, r.acct_id, 
                     r.desc_en, r.desc_ar, r.net_amnt, 1, 
                     C_DEFAULT_TAX_CODE, v_tax_pct, r.notes); 
            END LOOP; 
 
            UPDATE CRS_AGRM_CHECKING 
            SET    CHECK_STATUS = 6 
            WHERE  CHECKING_ID  = p_check_id; 
        END LOOP; 
    END checking_to_drnote; 
 
    -- ========================================================================= 
    PROCEDURE validate_drnote (p_drnote_id IN NUMBER) IS 
        v_doc_ref VARCHAR2(30); 
    BEGIN 
        FOR r IN ( 
            SELECT DRNOTE_ID, DOC_REF, COM_ID, LOC_ID 
            FROM   CRS_DRNOTE_HDRS 
            WHERE  DRNOTE_ID = p_drnote_id 
        ) LOOP 
            IF r.doc_ref IS NULL THEN 
                gen_doc_ref('CDRN', r.com_id, r.loc_id, 'CRS_DRNOTE_HDRS', v_doc_ref); 
                UPDATE CRS_DRNOTE_HDRS 
                SET    DOC_REF   = v_doc_ref 
                WHERE  DRNOTE_ID = p_drnote_id 
                AND    DOC_REF IS NULL; 
            END IF; 
 
            UPDATE CRS_DRNOTE_HDRS 
            SET    DRNOTE_STATUS = 2 
            WHERE  DRNOTE_ID     = p_drnote_id; 
        END LOOP; 
    END validate_drnote; 
 
