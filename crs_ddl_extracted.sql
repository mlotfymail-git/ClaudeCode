    PROCEDURE validate_checking (p_check_id IN NUMBER) IS 
        v_doc_ref VARCHAR2(30); 
    BEGIN 
        FOR r IN ( 
            SELECT checking_id, loc_id, com_id, agrm_id, reason_id, 
                   vin, out_in, check_date, doc_ref 
            FROM   V_CRS_AGRM_CHECKING 
            WHERE  checking_id = p_check_id 
        ) LOOP 
            -- Assign DOC_REF if not yet set 
            IF r.doc_ref IS NULL THEN 
                gen_doc_ref('CHCK', r.com_id, r.loc_id, 'CRS_AGRM_CHECKING', v_doc_ref); 
                UPDATE CRS_AGRM_CHECKING 
                SET    DOC_REF = v_doc_ref 
                WHERE  CHECKING_ID = p_check_id 
                AND    DOC_REF IS NULL; 
            END IF; 
 
            -- Advance checking status to "Validated" (2) 
            UPDATE CRS_AGRM_CHECKING 
            SET    CHECK_STATUS = 2 
            WHERE  CHECKING_ID  = r.checking_id; 
 
            -- Update car status and home location 
            -- Reasons 1-3: normal rental movements 
            UPDATE CRS_CARS 
            SET    CAR_STATUS = DECODE(r.OUT_IN, 'IN', 2, 'OUT', 3), 
                   LOC_ID     = r.loc_id 
            WHERE  VIN = r.vin 
            AND    r.reason_id IN (1, 2, 3); 
 
            -- Reasons 4-5: inspection movements 
            UPDATE CRS_CARS 
            SET    CAR_STATUS = 4, 
                   LOC_ID     = r.loc_id 
            WHERE  VIN = r.vin 
            AND    r.reason_id IN (4, 5); 
 
            -- Sync VIN on the agreement if it changed 
            UPDATE CRS_AGREEMENTS 
            SET    VIN = r.vin 
            WHERE  AGRM_ID = r.agrm_id 
            AND    VIN    <> r.vin; 
 
            -- Open the agreement on first check-out 
            UPDATE CRS_AGREEMENTS 
            SET    AGRM_STATUS = 3 
            WHERE  r.OUT_IN    = 'OUT' 
            AND    AGRM_ID     = r.agrm_id 
            AND    AGRM_STATUS <> 3; 
 
            -- Close the agreement on final return (reasons 2 or 5) 
            UPDATE CRS_AGREEMENTS 
            SET    AGRM_STATUS = 4, 
                   CLOSE_DATE  = r.check_date 
            WHERE  r.OUT_IN    = 'IN' 
            AND    r.reason_id IN (2, 5) 
            AND    AGRM_ID     = r.agrm_id 
            AND    AGRM_STATUS = 3; 
 
            -- Set agreement to "Waiting" on interim return (reasons 3 or 4) 
            UPDATE CRS_AGREEMENTS 
            SET    AGRM_STATUS = 5 
            WHERE  r.OUT_IN    = 'IN' 
            AND    r.reason_id IN (3, 4) 
            AND    AGRM_ID     = r.agrm_id 
            AND    AGRM_STATUS = 3; 
 
            -- Mark location as "Done" (LOC_FLAG = 'D') 
            UPDATE CRS_AGRM_LOCATIONS 
            SET    LOC_FLAG = 'D' 
            WHERE  OUT_IN   = r.OUT_IN 
            AND    AGRM_ID  = r.agrm_id 
            AND    LOC_ID   = r.loc_id; 
        END LOOP; 
    END validate_checking; 
 
