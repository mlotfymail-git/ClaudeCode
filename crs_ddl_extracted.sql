    v_prfx  VARCHAR2(10); 
    v_msr   NUMBER; 
BEGIN 
    IF INSERTING THEN 
        -- Generate document reference serial number 
        BEGIN 
            SELECT PREFIX, FIRST_SERIAL 
            INTO   v_prfx, v_msr 
            FROM   CRS_DOC_SERIAL 
            WHERE  DOC_CODE = 'CUST' 
            AND    COM_ID   = :NEW.COM_ID; 
        EXCEPTION 
            WHEN NO_DATA_FOUND THEN 
                RAISE_APPLICATION_ERROR(-20001, 
                    'No DOC_SERIAL configured for CUST / COM_ID=' || :NEW.COM_ID); 
        END; 
        SELECT v_prfx || NVL(MAX(TO_NUMBER(REPLACE(DOC_REF, v_prfx))) + 1, v_msr) 
        INTO   :NEW.DOC_REF 
        FROM   CRS_CUSTOMERS 
        WHERE  COM_ID = :NEW.COM_ID; 
 
        :NEW.CREATED_BY   := NVL(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER); 
        :NEW.CREATED_DATE := SYSTIMESTAMP; 
    END IF; 
    IF UPDATING THEN 
        :NEW.UPDATED_BY   := NVL(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER); 
        :NEW.UPDATED_DATE := SYSTIMESTAMP; 
    END IF; 
END BIUD_CRS_CUSTOMERS;
