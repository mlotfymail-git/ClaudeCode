    PROCEDURE gen_doc_ref ( 
        p_doc_code  IN  VARCHAR2, 
        p_com_id    IN  NUMBER, 
        p_loc_id    IN  NUMBER, 
        p_table     IN  VARCHAR2,   -- used only for error message 
        r_doc_ref   OUT VARCHAR2 
    ) IS 
        v_prfx  VARCHAR2(12); 
        v_msr   NUMBER; 
        v_sql   VARCHAR2(500); 
        v_next  NUMBER; 
    BEGIN 
        BEGIN 
            SELECT PREFIX, FIRST_SERIAL 
            INTO   v_prfx, v_msr 
            FROM   CRS_DOC_SERIAL 
            WHERE  DOC_CODE = p_doc_code 
            AND    COM_ID   = p_com_id 
            AND    LOC_ID   = p_loc_id; 
        EXCEPTION 
            WHEN NO_DATA_FOUND THEN 
                RAISE_APPLICATION_ERROR(-20012, 
                    'No DOC_SERIAL entry for '  || p_doc_code 
                    || ' COM=' || p_com_id || ' LOC=' || p_loc_id); 
        END; 
 
        -- Dynamic SQL to query the right table for MAX serial 
        v_sql :=  'SELECT NVL(MAX(TO_NUMBER(REPLACE(DOC_REF,:prfx)))+1,:msr) ' 
               || 'FROM ' || p_table 
               || ' WHERE LOC_ID = :loc'; 
        EXECUTE IMMEDIATE v_sql INTO v_next USING v_prfx, v_msr, p_loc_id; 
        r_doc_ref := v_prfx || v_next; 
    END gen_doc_ref; 
 
