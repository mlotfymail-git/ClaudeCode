    PROCEDURE validate_bill (p_bill_id IN NUMBER) IS 
        v_doc_ref VARCHAR2(30); 
    BEGIN 
        FOR r IN ( 
            SELECT BILL_ID, DOC_REF, COM_ID, LOC_ID 
            FROM   CRS_BILL_HDRS 
            WHERE  BILL_ID = p_bill_id 
        ) LOOP 
            IF r.doc_ref IS NULL THEN 
                gen_doc_ref('CRBL', r.com_id, r.loc_id, 'CRS_BILL_HDRS', v_doc_ref); 
                UPDATE CRS_BILL_HDRS 
                SET    DOC_REF = v_doc_ref 
                WHERE  BILL_ID = p_bill_id 
                AND    DOC_REF IS NULL; 
            END IF; 
 
            UPDATE CRS_BILL_HDRS 
            SET    BILL_STATUS = 2 
            WHERE  BILL_ID     = p_bill_id; 
        END LOOP; 
    END validate_bill; 
 
