-- ── 1. LOCATIONS ─────────────────────────────────────────────
CREATE TABLE LOCATIONS (
    LOCATION_ID     NUMBER          NOT NULL,
    LOCATION_CODE   VARCHAR2(10)    NOT NULL,   -- e.g. CAI-01
    NAME            VARCHAR2(100)   NOT NULL,
    ADDRESS         VARCHAR2(255),
    CITY            VARCHAR2(100)   NOT NULL,
    COUNTRY         VARCHAR2(100)   DEFAULT 'Egypt' NOT NULL,
    PHONE           VARCHAR2(20),
    EMAIL           VARCHAR2(100),
    MANAGER_ID      NUMBER,                     -- FK → EMPLOYEES (deferred)
    IS_ACTIVE       NUMBER(1)       DEFAULT 1   NOT NULL,
    CREATED_AT      DATE            DEFAULT SYSDATE NOT NULL,
    UPDATED_AT      DATE,
    CONSTRAINT PK_LOCATIONS        PRIMARY KEY (LOCATION_ID),
    CONSTRAINT UQ_LOCATION_CODE    UNIQUE (LOCATION_CODE),
    CONSTRAINT CK_LOC_ACTIVE       CHECK (IS_ACTIVE IN (0,1))
);

COMMENT ON TABLE  LOCATIONS              IS 'Rental branch / pickup-drop locations';
COMMENT ON COLUMN LOCATIONS.LOCATION_CODE IS 'Short unique code, e.g. CAI-01';


-- ── 2. CAR_CATEGORIES ────────────────────────────────────────
CREATE TABLE CAR_CATEGORIES (
    CATEGORY_ID     NUMBER          NOT NULL,
    NAME            VARCHAR2(50)    NOT NULL,   -- Economy, Compact, SUV, Luxury, Van
    DESCRIPTION     VARCHAR2(255),
    DAILY_RATE      NUMBER(10,2)    NOT NULL,
    DEPOSIT_AMOUNT  NUMBER(10,2)    DEFAULT 0   NOT NULL,
    IS_ACTIVE       NUMBER(1)       DEFAULT 1   NOT NULL,
    CREATED_AT      DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_CAR_CATEGORIES   PRIMARY KEY (CATEGORY_ID),
    CONSTRAINT UQ_CAT_NAME         UNIQUE (NAME),
    CONSTRAINT CK_CAT_DAILY_RATE   CHECK (DAILY_RATE > 0),
    CONSTRAINT CK_CAT_ACTIVE       CHECK (IS_ACTIVE IN (0,1))
);

COMMENT ON TABLE CAR_CATEGORIES IS 'Vehicle classification with base daily rates';


-- ── 3. CARS ──────────────────────────────────────────────────
CREATE TABLE CARS (
    CAR_ID          NUMBER          NOT NULL,
    PLATE_NUMBER    VARCHAR2(20)    NOT NULL,
    VIN             VARCHAR2(17),               -- Vehicle Identification Number
    MAKE            VARCHAR2(50)    NOT NULL,   -- Toyota, BMW …
    MODEL           VARCHAR2(50)    NOT NULL,
    YEAR            NUMBER(4)       NOT NULL,
    COLOR           VARCHAR2(30),
    CATEGORY_ID     NUMBER          NOT NULL,
    LOCATION_ID     NUMBER          NOT NULL,
    STATUS          VARCHAR2(15)    DEFAULT 'AVAILABLE' NOT NULL,
    MILEAGE         NUMBER(10)      DEFAULT 0   NOT NULL,
    FUEL_TYPE       VARCHAR2(15)    DEFAULT 'PETROL' NOT NULL,
    TRANSMISSION    VARCHAR2(10)    DEFAULT 'AUTO' NOT NULL,
    SEATS           NUMBER(2)       DEFAULT 5,
    DAILY_RATE_OVERRIDE NUMBER(10,2),           -- NULL = use category rate
    LAST_SERVICE_DATE   DATE,
    NEXT_SERVICE_DATE   DATE,
    CREATED_AT      DATE            DEFAULT SYSDATE NOT NULL,
    UPDATED_AT      DATE,
    CONSTRAINT PK_CARS             PRIMARY KEY (CAR_ID),
    CONSTRAINT UQ_PLATE_NUMBER     UNIQUE (PLATE_NUMBER),
    CONSTRAINT UQ_VIN              UNIQUE (VIN),
    CONSTRAINT FK_CAR_CATEGORY     FOREIGN KEY (CATEGORY_ID)  REFERENCES CAR_CATEGORIES(CATEGORY_ID),
    CONSTRAINT FK_CAR_LOCATION     FOREIGN KEY (LOCATION_ID)  REFERENCES LOCATIONS(LOCATION_ID),
    CONSTRAINT CK_CAR_STATUS       CHECK (STATUS IN ('AVAILABLE','RENTED','MAINTENANCE','RETIRED')),
    CONSTRAINT CK_CAR_FUEL         CHECK (FUEL_TYPE IN ('PETROL','DIESEL','ELECTRIC','HYBRID')),
    CONSTRAINT CK_CAR_TRANS        CHECK (TRANSMISSION IN ('AUTO','MANUAL')),
    CONSTRAINT CK_CAR_YEAR         CHECK (YEAR BETWEEN 1990 AND 2100),
    CONSTRAINT CK_CAR_MILEAGE      CHECK (MILEAGE >= 0)
);

COMMENT ON TABLE  CARS                       IS 'Vehicle inventory';
COMMENT ON COLUMN CARS.DAILY_RATE_OVERRIDE   IS 'If set, overrides category daily rate for this car';


-- ── 4. CUSTOMERS ─────────────────────────────────────────────
CREATE TABLE CUSTOMERS (
    CUSTOMER_ID     NUMBER          NOT NULL,
    FIRST_NAME      VARCHAR2(50)    NOT NULL,
    LAST_NAME       VARCHAR2(50)    NOT NULL,
    EMAIL           VARCHAR2(100)   NOT NULL,
    PHONE           VARCHAR2(20),
    NATIONAL_ID     VARCHAR2(20),
    LICENSE_NUMBER  VARCHAR2(30)    NOT NULL,
    LICENSE_EXPIRY  DATE            NOT NULL,
    LICENSE_COUNTRY VARCHAR2(50)    DEFAULT 'Egypt',
    DATE_OF_BIRTH   DATE,
    ADDRESS         VARCHAR2(255),
    CITY            VARCHAR2(100),
    COUNTRY         VARCHAR2(100)   DEFAULT 'Egypt',
    STATUS          VARCHAR2(15)    DEFAULT 'ACTIVE' NOT NULL,
    NOTES           VARCHAR2(500),
    CREATED_AT      DATE            DEFAULT SYSDATE NOT NULL,
    UPDATED_AT      DATE,
    CONSTRAINT PK_CUSTOMERS        PRIMARY KEY (CUSTOMER_ID),
    CONSTRAINT UQ_CUSTOMER_EMAIL   UNIQUE (EMAIL),
    CONSTRAINT UQ_LICENSE_NUMBER   UNIQUE (LICENSE_NUMBER),
    CONSTRAINT CK_CUST_STATUS      CHECK (STATUS IN ('ACTIVE','BLACKLISTED','SUSPENDED','INACTIVE')),
    CONSTRAINT CK_CUST_AGE         CHECK (DATE_OF_BIRTH IS NULL OR DATE_OF_BIRTH < SYSDATE - 6570)
    -- must be > 18 years old (6570 days)
);

COMMENT ON TABLE  CUSTOMERS IS 'Registered renters';
COMMENT ON COLUMN CUSTOMERS.STATUS IS 'ACTIVE=normal, BLACKLISTED=denied service, SUSPENDED=temporary hold';


-- ── 5. EMPLOYEES ─────────────────────────────────────────────
CREATE TABLE EMPLOYEES (
    EMPLOYEE_ID     NUMBER          NOT NULL,
    FIRST_NAME      VARCHAR2(50)    NOT NULL,
    LAST_NAME       VARCHAR2(50)    NOT NULL,
    EMAIL           VARCHAR2(100)   NOT NULL,
    PHONE           VARCHAR2(20),
    LOCATION_ID     NUMBER          NOT NULL,
    ROLE            VARCHAR2(15)    NOT NULL,
    HIRE_DATE       DATE            DEFAULT SYSDATE NOT NULL,
    STATUS          VARCHAR2(10)    DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      DATE            DEFAULT SYSDATE NOT NULL,
    UPDATED_AT      DATE,
    CONSTRAINT PK_EMPLOYEES        PRIMARY KEY (EMPLOYEE_ID),
    CONSTRAINT UQ_EMP_EMAIL        UNIQUE (EMAIL),
    CONSTRAINT FK_EMP_LOCATION     FOREIGN KEY (LOCATION_ID) REFERENCES LOCATIONS(LOCATION_ID),
    CONSTRAINT CK_EMP_ROLE         CHECK (ROLE IN ('MANAGER','AGENT','MECHANIC','ADMIN')),
    CONSTRAINT CK_EMP_STATUS       CHECK (STATUS IN ('ACTIVE','INACTIVE','TERMINATED'))
);

-- Back-fill manager FK now that EMPLOYEES exists
ALTER TABLE LOCATIONS ADD CONSTRAINT FK_LOC_MANAGER
    FOREIGN KEY (MANAGER_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID);

COMMENT ON TABLE EMPLOYEES IS 'Staff members per location';


-- ── 6. INSURANCE_PLANS ───────────────────────────────────────
CREATE TABLE INSURANCE_PLANS (
    PLAN_ID         NUMBER          NOT NULL,
    NAME            VARCHAR2(50)    NOT NULL,   -- Basic, Standard, Premium, Full
    DESCRIPTION     VARCHAR2(255),
    DAILY_RATE      NUMBER(8,2)     NOT NULL,
    COVERAGE_AMOUNT NUMBER(12,2)    NOT NULL,
    DEDUCTIBLE      NUMBER(10,2)    DEFAULT 0,
    IS_ACTIVE       NUMBER(1)       DEFAULT 1   NOT NULL,
    CREATED_AT      DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_INSURANCE_PLANS  PRIMARY KEY (PLAN_ID),
    CONSTRAINT UQ_INS_NAME         UNIQUE (NAME),
    CONSTRAINT CK_INS_ACTIVE       CHECK (IS_ACTIVE IN (0,1)),
    CONSTRAINT CK_INS_RATE         CHECK (DAILY_RATE >= 0)
);

COMMENT ON TABLE INSURANCE_PLANS IS 'Available insurance coverage options';


-- ── 7. RESERVATIONS ──────────────────────────────────────────
CREATE TABLE RESERVATIONS (
    RESERVATION_ID      NUMBER          NOT NULL,
    CUSTOMER_ID         NUMBER          NOT NULL,
    CAR_ID              NUMBER          NOT NULL,
    PICKUP_LOCATION_ID  NUMBER          NOT NULL,
    RETURN_LOCATION_ID  NUMBER          NOT NULL,
    PICKUP_DATE         DATE            NOT NULL,
    RETURN_DATE         DATE            NOT NULL,
    INSURANCE_PLAN_ID   NUMBER,
    STATUS              VARCHAR2(15)    DEFAULT 'PENDING' NOT NULL,
    ESTIMATED_AMOUNT    NUMBER(12,2),
    DISCOUNT_PCT        NUMBER(5,2)     DEFAULT 0,
    NOTES               VARCHAR2(500),
    CREATED_AT          DATE            DEFAULT SYSDATE NOT NULL,
    CREATED_BY          NUMBER,                 -- FK EMPLOYEES
    UPDATED_AT          DATE,
    CONSTRAINT PK_RESERVATIONS         PRIMARY KEY (RESERVATION_ID),
    CONSTRAINT FK_RES_CUSTOMER         FOREIGN KEY (CUSTOMER_ID)        REFERENCES CUSTOMERS(CUSTOMER_ID),
    CONSTRAINT FK_RES_CAR              FOREIGN KEY (CAR_ID)             REFERENCES CARS(CAR_ID),
    CONSTRAINT FK_RES_PICKUP_LOC       FOREIGN KEY (PICKUP_LOCATION_ID) REFERENCES LOCATIONS(LOCATION_ID),
    CONSTRAINT FK_RES_RETURN_LOC       FOREIGN KEY (RETURN_LOCATION_ID) REFERENCES LOCATIONS(LOCATION_ID),
    CONSTRAINT FK_RES_INSURANCE        FOREIGN KEY (INSURANCE_PLAN_ID)  REFERENCES INSURANCE_PLANS(PLAN_ID),
    CONSTRAINT FK_RES_CREATED_BY       FOREIGN KEY (CREATED_BY)         REFERENCES EMPLOYEES(EMPLOYEE_ID),
    CONSTRAINT CK_RES_STATUS           CHECK (STATUS IN ('PENDING','CONFIRMED','CANCELLED','NO_SHOW','COMPLETED')),
    CONSTRAINT CK_RES_DATES            CHECK (RETURN_DATE > PICKUP_DATE),
    CONSTRAINT CK_RES_DISCOUNT         CHECK (DISCOUNT_PCT BETWEEN 0 AND 100)
);

COMMENT ON TABLE RESERVATIONS IS 'Pre-bookings before actual car pickup';


-- ── 8. RENTALS ───────────────────────────────────────────────
CREATE TABLE RENTALS (
    RENTAL_ID               NUMBER          NOT NULL,
    RESERVATION_ID          NUMBER,                     -- nullable: walk-in rental
    CUSTOMER_ID             NUMBER          NOT NULL,
    CAR_ID                  NUMBER          NOT NULL,
    AGENT_ID                NUMBER          NOT NULL,   -- employee who opened rental
    PICKUP_LOCATION_ID      NUMBER          NOT NULL,
    RETURN_LOCATION_ID      NUMBER          NOT NULL,
    ACTUAL_PICKUP_DATE      DATE            NOT NULL,
    EXPECTED_RETURN_DATE    DATE            NOT NULL,
    ACTUAL_RETURN_DATE      DATE,
    PICKUP_MILEAGE          NUMBER(10)      NOT NULL,
    RETURN_MILEAGE          NUMBER(10),
    PICKUP_FUEL_LEVEL       VARCHAR2(10)    DEFAULT 'FULL',
    RETURN_FUEL_LEVEL       VARCHAR2(10),
    STATUS                  VARCHAR2(10)    DEFAULT 'ACTIVE' NOT NULL,
    BASE_AMOUNT             NUMBER(12,2)    NOT NULL,
    EXTRA_CHARGES           NUMBER(12,2)    DEFAULT 0,
    FUEL_CHARGE             NUMBER(10,2)    DEFAULT 0,
    DISCOUNT_AMOUNT         NUMBER(10,2)    DEFAULT 0,
    TOTAL_AMOUNT            NUMBER(12,2),
    INSURANCE_PLAN_ID       NUMBER,
    INSURANCE_AMOUNT        NUMBER(10,2)    DEFAULT 0,
    NOTES                   VARCHAR2(500),
    CREATED_AT              DATE            DEFAULT SYSDATE NOT NULL,
    UPDATED_AT              DATE,
    CONSTRAINT PK_RENTALS              PRIMARY KEY (RENTAL_ID),
    CONSTRAINT FK_RNT_RESERVATION      FOREIGN KEY (RESERVATION_ID)     REFERENCES RESERVATIONS(RESERVATION_ID),
    CONSTRAINT FK_RNT_CUSTOMER         FOREIGN KEY (CUSTOMER_ID)        REFERENCES CUSTOMERS(CUSTOMER_ID),
    CONSTRAINT FK_RNT_CAR              FOREIGN KEY (CAR_ID)             REFERENCES CARS(CAR_ID),
    CONSTRAINT FK_RNT_AGENT            FOREIGN KEY (AGENT_ID)           REFERENCES EMPLOYEES(EMPLOYEE_ID),
    CONSTRAINT FK_RNT_PICKUP_LOC       FOREIGN KEY (PICKUP_LOCATION_ID) REFERENCES LOCATIONS(LOCATION_ID),
    CONSTRAINT FK_RNT_RETURN_LOC       FOREIGN KEY (RETURN_LOCATION_ID) REFERENCES LOCATIONS(LOCATION_ID),
    CONSTRAINT FK_RNT_INSURANCE        FOREIGN KEY (INSURANCE_PLAN_ID)  REFERENCES INSURANCE_PLANS(PLAN_ID),
    CONSTRAINT CK_RNT_STATUS           CHECK (STATUS IN ('ACTIVE','COMPLETED','OVERDUE','CANCELLED')),
    CONSTRAINT CK_RNT_DATES            CHECK (EXPECTED_RETURN_DATE > ACTUAL_PICKUP_DATE),
    CONSTRAINT CK_RNT_FUEL_LVL        CHECK (PICKUP_FUEL_LEVEL  IN ('FULL','3/4','1/2','1/4','EMPTY')),
    CONSTRAINT CK_RNT_FUEL_RTN        CHECK (RETURN_FUEL_LEVEL IS NULL OR RETURN_FUEL_LEVEL IN ('FULL','3/4','1/2','1/4','EMPTY'))
);

COMMENT ON TABLE RENTALS IS 'Active and historical rental transactions';


-- ── 9. PAYMENTS ──────────────────────────────────────────────
CREATE TABLE PAYMENTS (
    PAYMENT_ID          NUMBER          NOT NULL,
    RENTAL_ID           NUMBER          NOT NULL,
    AMOUNT              NUMBER(12,2)    NOT NULL,
    PAYMENT_DATE        DATE            DEFAULT SYSDATE NOT NULL,
    PAYMENT_METHOD      VARCHAR2(15)    NOT NULL,
    STATUS              VARCHAR2(15)    DEFAULT 'COMPLETED' NOT NULL,
    REFERENCE_NUMBER    VARCHAR2(50),
    NOTES               VARCHAR2(255),
    CREATED_BY          NUMBER,
    CREATED_AT          DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_PAYMENTS             PRIMARY KEY (PAYMENT_ID),
    CONSTRAINT FK_PAY_RENTAL           FOREIGN KEY (RENTAL_ID)   REFERENCES RENTALS(RENTAL_ID),
    CONSTRAINT FK_PAY_CREATED_BY       FOREIGN KEY (CREATED_BY)  REFERENCES EMPLOYEES(EMPLOYEE_ID),
    CONSTRAINT CK_PAY_METHOD           CHECK (PAYMENT_METHOD IN ('CASH','VISA','MASTERCARD','BANK_TRANSFER','CHEQUE')),
    CONSTRAINT CK_PAY_STATUS           CHECK (STATUS IN ('PENDING','COMPLETED','REFUNDED','FAILED')),
    CONSTRAINT CK_PAY_AMOUNT           CHECK (AMOUNT <> 0)
);

COMMENT ON TABLE PAYMENTS IS 'Payment transactions linked to rentals';


-- ── 10. DAMAGE_REPORTS ───────────────────────────────────────
CREATE TABLE DAMAGE_REPORTS (
    DAMAGE_ID       NUMBER          NOT NULL,
    RENTAL_ID       NUMBER          NOT NULL,
    CAR_ID          NUMBER          NOT NULL,
    REPORTED_BY     NUMBER          NOT NULL,   -- employee
    REPORT_DATE     DATE            DEFAULT SYSDATE NOT NULL,
    DAMAGE_TYPE     VARCHAR2(20)    NOT NULL,
    DESCRIPTION     VARCHAR2(1000)  NOT NULL,
    REPAIR_COST     NUMBER(10,2),
    CHARGED_TO_CUSTOMER NUMBER(1)   DEFAULT 0,
    STATUS          VARCHAR2(15)    DEFAULT 'REPORTED' NOT NULL,
    RESOLVED_DATE   DATE,
    NOTES           VARCHAR2(500),
    CREATED_AT      DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_DAMAGE_REPORTS   PRIMARY KEY (DAMAGE_ID),
    CONSTRAINT FK_DMG_RENTAL       FOREIGN KEY (RENTAL_ID)   REFERENCES RENTALS(RENTAL_ID),
    CONSTRAINT FK_DMG_CAR          FOREIGN KEY (CAR_ID)      REFERENCES CARS(CAR_ID),
    CONSTRAINT FK_DMG_REPORTER     FOREIGN KEY (REPORTED_BY) REFERENCES EMPLOYEES(EMPLOYEE_ID),
    CONSTRAINT CK_DMG_TYPE         CHECK (DAMAGE_TYPE IN ('SCRATCH','DENT','GLASS','TIRE','MECHANICAL','TOTAL_LOSS','OTHER')),
    CONSTRAINT CK_DMG_STATUS       CHECK (STATUS IN ('REPORTED','ASSESSED','IN_REPAIR','RESOLVED')),
    CONSTRAINT CK_DMG_CHARGED      CHECK (CHARGED_TO_CUSTOMER IN (0,1))
);

COMMENT ON TABLE DAMAGE_REPORTS IS 'Vehicle damage recorded at return or inspection';


-- ── 11. MAINTENANCE ──────────────────────────────────────────
CREATE TABLE MAINTENANCE (
    MAINTENANCE_ID  NUMBER          NOT NULL,
    CAR_ID          NUMBER          NOT NULL,
    TYPE            VARCHAR2(15)    NOT NULL,
    DESCRIPTION     VARCHAR2(500),
    START_DATE      DATE            NOT NULL,
    END_DATE        DATE,
    COST            NUMBER(10,2)    DEFAULT 0,
    PERFORMED_BY    NUMBER,                     -- employee (mechanic)
    LOCATION_ID     NUMBER          NOT NULL,
    STATUS          VARCHAR2(15)    DEFAULT 'SCHEDULED' NOT NULL,
    CREATED_AT      DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_MAINTENANCE      PRIMARY KEY (MAINTENANCE_ID),
    CONSTRAINT FK_MNT_CAR          FOREIGN KEY (CAR_ID)        REFERENCES CARS(CAR_ID),
    CONSTRAINT FK_MNT_EMPLOYEE     FOREIGN KEY (PERFORMED_BY)  REFERENCES EMPLOYEES(EMPLOYEE_ID),
    CONSTRAINT FK_MNT_LOCATION     FOREIGN KEY (LOCATION_ID)   REFERENCES LOCATIONS(LOCATION_ID),
    CONSTRAINT CK_MNT_TYPE         CHECK (TYPE IN ('ROUTINE','REPAIR','INSPECTION','CLEANING','UPGRADE')),
    CONSTRAINT CK_MNT_STATUS       CHECK (STATUS IN ('SCHEDULED','IN_PROGRESS','COMPLETED','CANCELLED'))
);

COMMENT ON TABLE MAINTENANCE IS 'Vehicle maintenance and service records';


-- ── 12. AUDIT_LOG ────────────────────────────────────────────
CREATE TABLE AUDIT_LOG (
    LOG_ID          NUMBER          NOT NULL,
    TABLE_NAME      VARCHAR2(50)    NOT NULL,
    OPERATION       VARCHAR2(10)    NOT NULL,   -- INSERT, UPDATE, DELETE
    RECORD_ID       NUMBER          NOT NULL,
    OLD_VALUES      CLOB,
    NEW_VALUES      CLOB,
    CHANGED_BY      VARCHAR2(100)   DEFAULT USER NOT NULL,
    CHANGED_AT      DATE            DEFAULT SYSDATE NOT NULL,
    APP_USER        VARCHAR2(100),              -- application-level user
    IP_ADDRESS      VARCHAR2(45),
    CONSTRAINT PK_AUDIT_LOG        PRIMARY KEY (LOG_ID),
    CONSTRAINT CK_AUDIT_OPERATION  CHECK (OPERATION IN ('INSERT','UPDATE','DELETE'))
)
-- Partition by month for performance (optional, uncomment if partitioning is licensed)
-- PARTITION BY RANGE (CHANGED_AT) INTERVAL (NUMTOYMINTERVAL(1,'MONTH'))
-- (PARTITION P_INIT VALUES LESS THAN (DATE '2024-01-01'))
;

COMMENT ON TABLE  AUDIT_LOG           IS 'Full audit trail for critical tables';
COMMENT ON COLUMN AUDIT_LOG.OLD_VALUES IS 'JSON-style old column values';
COMMENT ON COLUMN AUDIT_LOG.NEW_VALUES IS 'JSON-style new column values';
